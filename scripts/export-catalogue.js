const fs = require('fs');
const D = '/Users/apporva-vh/partner-opportunity-agent/data/';
const r = (f) => JSON.parse(fs.readFileSync(D + f, 'utf8'));
const out = [];
const w = (s = '') => out.push(s);

w('# Lyzr Emerging Partners — the full catalogue');
w();
w('Everything the opportunity agent reasons from. Generated from `data/` on ' + new Date().toISOString().slice(0, 10) + '.');
w();

/* ---------- 1. platform products ---------- */
const prods = r('partner-offerings.json').offerings;
w('## 1. Platform products (' + prods.length + ')');
w();
w('`data/partner-offerings.json` — hand-written. The only records carrying commercial terms.');
w();
for (const p of prods) {
  w('### ' + p.name);
  w();
  w('- **id** `' + p.offering_id + '` · **motion** `' + p.commercial_motion + '` · **page** ' + p.url);
  w('- **What it is** ' + p.one_line);
  w('- **Buyer** ' + p.buyer);
  w('- **Trigger** ' + p.trigger);
  w('- **Follow-on revenue** ' + p.follow_on);
  w();
  w('**Capabilities**');
  for (const c of p.capabilities ?? []) w('- ' + c);
  w();
  w('**Sits next to**');
  for (const c of p.complements ?? []) w('- ' + c);
  w();
  w('**Services a partner could sell**');
  for (const c of p.sellable_services ?? []) w('- ' + (typeof c === 'string' ? c : `**${c.name}** ${c.client_gets ?? ''}`));
  w();
  if (p.revenue) {
    w('**Revenue**');
    for (const [k, v] of Object.entries(p.revenue)) w('- *' + k + '* — ' + v);
    w();
  }
  w('**Customer problems it addresses**');
  for (const c of p.customer_problems ?? []) w('- ' + c);
  w();
  w('**Eligibility requires**');
  w('- families: `' + (p.requires?.families ?? []).join('`, `') + '`');
  w('- signals: `' + (p.requires?.signals ?? []).join('`, `') + '`');
  if (p.requires?.why) w('- why: ' + p.requires.why);
  w();
  if ((p.prerequisites ?? []).length) { w('**Prerequisites**'); for (const c of p.prerequisites) w('- ' + c); w(); }
  if ((p.do_not_recommend_when ?? []).length) { w('**Do not recommend when**'); for (const c of p.do_not_recommend_when) w('- ' + c); w(); }
  if ((p.restrictions ?? []).length) { w('**Restrictions (what we may not promise)**'); for (const c of p.restrictions) w('- ' + c); w(); }
  w('---');
  w();
}

/* ---------- 2. solutions ---------- */
const sols = r('solution-offerings.json').offerings;
const seg = sols.filter((s) => s.industry);
const horiz = sols.filter((s) => !s.industry);
w('## 2. Packaged solutions (' + sols.length + ')');
w();
w('`data/solution-offerings.json` — generated by `scripts/build-solution-offerings.js` from the catalogue. All run the `solution_to_segment` motion.');
w();
w('### 2a. Tied to an industry (' + seg.length + ') — the segment plays');
w();
w('| Industry | Solution | id |');
w('|---|---|---|');
for (const s of seg) w('| ' + s.industry + ' | ' + s.name + ' | `' + s.offering_id + '` |');
w();
w('### 2b. Horizontal / named agents (' + horiz.length + ')');
w();
w('| Solution | id |');
w('|---|---|');
for (const s of horiz) w('| ' + s.name + ' | `' + s.offering_id + '` |');
w();
w('### 2c. Every solution in full');
w();
for (const s of sols) {
  w('#### ' + s.name + (s.industry ? ' — *' + s.industry + '*' : ''));
  w();
  w('- **id** `' + s.offering_id + '` · **built on** `' + s.product_id + '` · ' + (s.url ?? ''));
  w('- ' + (s.one_line ?? ''));
  if (s.buyer) w('- **Buyer** ' + s.buyer);
  if (s.trigger) w('- **Trigger** ' + s.trigger);
  if ((s.capabilities ?? []).length) { w(); w('**Capabilities**'); for (const c of s.capabilities) w('- ' + c); }
  if ((s.sellable_services ?? []).length) { w(); w('**Services a partner could sell**'); for (const c of s.sellable_services) w('- ' + (typeof c === 'string' ? c : `**${c.name}** ${c.client_gets ?? ''}`)); }
  if ((s.customer_problems ?? []).length) { w(); w('**Customer problems**'); for (const c of s.customer_problems) w('- ' + c); }
  if (s.revenue) { w(); w('**Revenue**'); for (const [k, v] of Object.entries(s.revenue)) w('- *' + k + '* — ' + v); }
  w();
  w('**Eligibility requires** families: `' + (s.requires?.families ?? []).join('`, `') + '` · signals: `' + (s.requires?.signals ?? []).join('`, `') + '`');
  w();
}
w('---');
w();

/* ---------- 3. motions ---------- */
const mot = r('motions.json').motions;
w('## 3. Commercial motions (' + mot.length + ')');
w();
w('`data/motions.json`. One recommendation per motion: three cards on one motion are three versions of the same meeting.');
w();
for (const m of mot) {
  w('### ' + m.label + '  `' + m.id + '`');
  w();
  w('- ' + m.what);
  w('- **Sells to** ' + m.sells_to);
  w('- **Needs from the partner** ' + m.needs);
  w();
}
w('---');
w();

/* ---------- 4. patterns ---------- */
const pats = r('patterns.json').patterns;
w('## 4. Engagement shapes (' + pats.length + ')');
w();
w('`data/patterns.json`. Durations, staffing and revenue are written here and never by a model. `{work}` and `{unit}` are filled per opportunity.');
w();
for (const p of pats) {
  w('### `' + p.id + '` — ' + p.growth_path);
  w();
  w('- **When** ' + p.when);
  w('- **First offer** ' + p.first_offer.name + ' — ' + p.first_offer.shape + ', ends with ' + p.first_offer.ends_with);
  w('- **Delivery** ' + p.delivery.shape + ' (' + p.delivery.team_needed + ')');
  w('- **Expansion** ' + p.expansion);
  if (p.revenue) { w(); w('**Revenue streams**'); for (const [k, v] of Object.entries(p.revenue)) w('- *' + k + '* — ' + v); }
  w();
  w('**Discovery questions**');
  for (const q of p.discovery ?? []) w('- ' + q);
  w();
  w('**Roles** — partner: ' + p.roles.partner + ' · Lyzr: ' + p.roles.lyzr);
  w();
}
w('---');
w();

/* ---------- 5. catalog ---------- */
const cat = Object.values(r('catalog.json').records);
w('## 5. Lyzr record catalogue (' + cat.length + ')');
w();
w('`data/catalog.json` — built by `scripts/build-catalog.js` from lyzr.ai. This is the evidence layer: what Lyzr has delivered, offers, or can do.');
w();
const byKind = {};
for (const c of cat) (byKind[c.kind] ??= []).push(c);
for (const [kind, list] of Object.entries(byKind)) {
  w('### ' + kind + ' (' + list.length + ')');
  w();
  w('| Title | Industry | Client | Confidence |');
  w('|---|---|---|---|');
  for (const c of list) w('| ' + (c.title ?? '').replace(/\|/g, '/') + ' | ' + (c.industry ?? '') + ' | ' + (c.client ?? '') + ' | ' + (c.confidence ?? '') + ' |');
  w();
}
w('---');
w();

/* ---------- 6. resources ---------- */
const res = r('resources.json').resources;
w('## 6. Resources (' + res.length + ')');
w();
w('`data/resources.json`. Shelved See it / Build it / Sell it at runtime by `lib/resources.js`, not stored.');
w();
w('| Title | Type | URL |');
w('|---|---|---|');
for (const x of res) w('| ' + (x.title ?? '').replace(/\|/g, '/') + ' | ' + (x.type ?? '') + ' | ' + (x.url ?? '') + ' |');
w();

/* ---------- 7. the rest ---------- */
w('---');
w();
w('## 7. Other files in `data/`');
w();
w('| File | What it is |');
w('|---|---|');
w('| `brief-template.json` | The fixed scaffold of the brief. Every partner gets these words. |');
w('| `products.json` | Platform/agent names used for "what you could demo". |');
w('| `proof.json` | Proof points kept separately from the catalogue. |');
w('| `landing-copy.json` | Patch list applied to the landing page. |');

fs.writeFileSync('/Users/apporva-vh/partner-opportunity-agent/CATALOGUE.md', out.join('\n') + '\n');
console.log('wrote CATALOGUE.md —', out.length, 'lines');
